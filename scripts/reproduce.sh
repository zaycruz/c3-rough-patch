#!/usr/bin/env bash
# One command from the sponsor download to every number in README.md.
#   scripts/reproduce.sh [DATA_DIR] [full|quick]
#   DATA_DIR: the unzipped Challenge3_Bad_Week_Radar folder (default: data/Challenge3_Bad_Week_Radar). See data/README.md.
#   quick: served pipeline only. full (default): also the historical label cross-check and the proxy-label run.
# Writes analysis/out/*, analysis/out/historical/*, src/data/*.json and runs/reproduce-<UTC stamp>.md (the log).
# Needs: uv (it installs Python 3.14 and the locked packages), git, and the full git history (not a shallow clone).
# Fixed seeds everywhere (SEED in analysis/train.py). CPU only, about 6 GB RAM.
set -euo pipefail
cd "$(dirname "$0")/.."
DATA="$(cd "${1:-data/Challenge3_Bad_Week_Radar}" && pwd)"
MODE="${2:-full}"
HIST_COMMIT=d72545d   # label v2 before check-ins became inputs: the cross-check and proxy-label numbers come from here
STAMP="$(date -u +%Y-%m-%dT%H-%M-%SZ)"
mkdir -p runs analysis/out/historical
# a fresh clone already holds every output; delete what the checker reads so a "match" means "regenerated by this run"
rm -f analysis/out/*.json src/data/survivors.json src/data/metrics.json public/api/c3/survivors
[ "$MODE" = full ] && rm -f analysis/out/historical/metrics_v2_*.json analysis/out/historical/label_crosscheck.json analysis/out/historical/exp_checkin_worklist_*.json  # metrics_v1_baseline.json is a kept record, not regenerated
LOG="runs/reproduce-$STAMP.md"
RAW="runs/reproduce-$STAMP.log"
PY=(uv run --frozen --no-sync python -I)
sha() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }

{
  echo "# C3 reproduce run $STAMP"
  echo
  echo "- Where: ${REPRO_WHERE:-$(uname -srm) on $(hostname)}"
  echo "- Commit: $(git rev-parse HEAD) ($(git log -1 --format=%s | cut -c1-80))"
  echo "- Mode: $MODE · data: \`$DATA\`"
  echo "- uv: $(uv --version)"
} > "$LOG"

echo "## Data check (sha256)" >> "$LOG"
ok=1
while read -r want file; do
  got="$(sha "$DATA/$file" 2>/dev/null || echo missing)"
  if [ "$got" = "$want" ]; then echo "- ok \`$file\`" >> "$LOG"; else echo "- **FAIL** \`$file\`: $got" >> "$LOG"; ok=0; fi
done <<'SUMS'
6d9b500ed5fa41ce0eb0f847351abf238623e90d20d534df0c7ea1774eb2a3b7 synthetic_data/synthetic_daily.csv
81a65878cf4e8ff04d1986b9b874d67acae129732e3e5a700943b5a98151cc18 synthetic_data/synthetic_patients.csv
8ed37e47cf37ddbef74266f350a1112437af80bc9496e1f74be33d55ae71dc2b fatigue_study_daily.csv
SUMS
[ "$ok" = 1 ] || { echo "data check failed, see $LOG"; cat "$LOG"; exit 2; }

uv sync --frozen >> "$RAW" 2>&1
echo "- Python: $("${PY[@]}" -c 'import sys,numpy,pandas,sklearn,pyarrow;print(sys.version.split()[0],"numpy",numpy.__version__,"pandas",pandas.__version__,"scikit-learn",sklearn.__version__,"pyarrow",pyarrow.__version__)')" >> "$LOG"
echo >> "$LOG"
echo "## Steps" >> "$LOG"
echo "| Step | Command | Seconds | Peak RAM (MB) |" >> "$LOG"
echo "|---|---|---|---|" >> "$LOG"
T0=$SECONDS
step() {  # step "<name>" cmd...
  local name="$1"; shift
  local t=$SECONDS
  echo ">>> $name: $*" | tee -a "$RAW"
  local err; err="$(mktemp)"
  "${PY[@]}" scripts/peakmem.py "$@" >> "$RAW" 2> "$err" || { cat "$err" >> "$RAW"; echo "| $name | \`$*\` | FAILED | |" >> "$LOG"; tail -40 "$RAW"; exit 1; }
  grep -v '^PEAK_MB=' "$err" >> "$RAW" || true
  echo "| $name | \`$*\` | $((SECONDS - t)) | $(grep -o 'PEAK_MB=[0-9]*' "$err" | cut -d= -f2) |" >> "$LOG"
  rm -f "$err"
}

step "train (served model)" "${PY[@]}" analysis/train.py "$DATA"
step "real-data check" "${PY[@]}" analysis/real_check.py "$DATA"
step "diary-note red-flag scan (self-test + eval)" "${PY[@]}" analysis/notes_scan.py
step "urgent tier + note scan CIs" "${PY[@]}" analysis/urgent_ci.py
step "model-free escalation (note, ideation, check-in rules)" "${PY[@]}" analysis/escalation.py
step "notes as model inputs (experiment)" "${PY[@]}" analysis/exp/notes_features.py
step "export to src/data + static roster" env C3_DATA="$DATA" C3_RUN_ID="reproduce-$STAMP" "${PY[@]}" analysis/export.py
step "ER pre-signal" "${PY[@]}" analysis/exp/er_presignal.py "$DATA"

if [ "$MODE" = full ]; then
  H="$(mktemp -d)"; mkdir -p "$H/analysis/out"
  git show "$HIST_COMMIT:analysis/train.py" > "$H/analysis/train.py"
  step "historical train @$HIST_COMMIT (label v2, no proxy)" "${PY[@]}" "$H/analysis/train.py" "$DATA"
  cp "$H/analysis/out/metrics.json" analysis/out/historical/metrics_v2_noproxy.json
  step "label cross-check, matched 12% budget" "${PY[@]}" analysis/exp/label_crosscheck.py "$H/analysis"
  cp "$H/analysis/out/label_crosscheck.json" analysis/out/historical/
  # the check-in / surprise / worklist experiment was run on these outputs (wearable + calendar model, before check-ins)
  mkdir -p "$H/analysis/exp" && cp analysis/exp/checkin_worklist.py "$H/analysis/exp/"
  step "check-in experiment (val) on @$HIST_COMMIT outputs" env EVAL=val "${PY[@]}" "$H/analysis/exp/checkin_worklist.py"
  step "check-in experiment (test) on @$HIST_COMMIT outputs" env EVAL=test "${PY[@]}" "$H/analysis/exp/checkin_worklist.py"
  cp "$H"/analysis/out/exp_checkin_worklist_*.json analysis/out/historical/
  step "historical train @$HIST_COMMIT (C3_PROXY=1)" env C3_PROXY=1 "${PY[@]}" "$H/analysis/train.py" "$DATA"
  cp "$H/analysis/out/metrics.json" analysis/out/historical/metrics_v2_proxy.json
  rm -rf "$H"
fi
echo "| **total** | | $((SECONDS - T0)) | |" >> "$LOG"

echo >> "$LOG"
echo "## README numbers vs this run" >> "$LOG"
set +e
"${PY[@]}" scripts/check_numbers.py . "$MODE" >> "$LOG"; rc=$?
set -e
echo >> "$LOG"
echo "## Served files vs the committed ones" >> "$LOG"
echo '```' >> "$LOG"
git diff --stat -- src/data analysis/out >> "$LOG" 2>&1 || true
echo '```' >> "$LOG"
echo >> "$LOG"
if [ $rc = 0 ]; then echo "**PASS**: every README number matched (rows marked "platform tolerance" are within the documented macOS/Linux tolerance, see REPRODUCE.md)." >> "$LOG"; else echo "**FAIL**: see MISMATCH / MISSING rows above." >> "$LOG"; fi
echo "log: $LOG (raw output: $RAW)"
exit $rc
